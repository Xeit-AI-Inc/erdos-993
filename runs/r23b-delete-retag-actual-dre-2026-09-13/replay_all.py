def poly_add(a, b):
    n = max(len(a), len(b))
    out = [0] * n
    for i, x in enumerate(a):
        out[i] += x
    for i, x in enumerate(b):
        out[i] += x
    return out


def poly_mul(a, b):
    if not a or not b:
        return [0]
    out = [0] * (len(a) + len(b) - 1)
    for i, ai in enumerate(a):
        if not ai:
            continue
        for j, bj in enumerate(b):
            if bj:
                out[i + j] += ai * bj
    return out


def poly_shift(a):
    return [0] + list(a)


def coef(poly, k):
    return poly[k] if 0 <= k < len(poly) else 0


def delta(poly, k):
    return coef(poly, k + 1) - coef(poly, k)


def first_strict_descent(poly, guard=None):
    k = 0
    limit = guard if guard is not None else (len(poly) + 3)
    while True:
        if delta(poly, k) < 0:
            return k
        k += 1
        if k > limit:
            raise RuntimeError("no strict descent found within guard bound")


def adjacency(n, edges):
    adj = [set() for _ in range(n)]
    for a, b in edges:
        adj[a].add(b)
        adj[b].add(a)
    return adj


def induced_components(adj, vertices):
    vertices = set(vertices)
    seen, comps = set(), []
    for start in vertices:
        if start in seen:
            continue
        comp, stack = set(), [start]
        seen.add(start)
        while stack:
            u = stack.pop()
            comp.add(u)
            for w in adj[u]:
                if w in vertices and w not in seen:
                    seen.add(w)
                    stack.append(w)
        comps.append(comp)
    return comps


def dp_indep_poly_tree(adj, vertices):
    vertices = list(vertices)
    if not vertices:
        return [1]
    root = min(vertices)
    vset = set(vertices)
    parent = {root: None}
    order = [root]
    stack = [root]
    visited = {root}
    while stack:
        u = stack.pop()
        for w in adj[u]:
            if w in vset and w not in visited:
                visited.add(w)
                parent[w] = u
                order.append(w)
                stack.append(w)
    assert len(order) == len(vertices), "induced set is not one tree component"
    children = {v: [] for v in vertices}
    for v in order[1:]:
        children[parent[v]].append(v)
    A, B = {}, {}
    for v in reversed(order):
        a_poly, b_poly = [1], [1]
        for c in children[v]:
            a_poly = poly_mul(a_poly, poly_add(A[c], B[c]))
            b_poly = poly_mul(b_poly, A[c])
        A[v] = a_poly
        B[v] = poly_shift(b_poly)
    return poly_add(A[root], B[root])


def dp_indep_poly(adj, vertices):
    poly = [1]
    for comp in induced_components(adj, vertices):
        poly = poly_mul(poly, dp_indep_poly_tree(adj, comp))
    return poly


BRUTE_MAX_N = 22  # 2^22 subset-scan ceiling for the independent cross-check


def brute_indep_poly(adj, vertices):
    verts = sorted(vertices)
    m = len(verts)
    if m > BRUTE_MAX_N:
        return None
    idx = {v: i for i, v in enumerate(verts)}
    nbmask = [0] * m
    for v in verts:
        mv = 0
        for w in adj[v]:
            if w in idx:
                mv |= (1 << idx[w])
        nbmask[idx[v]] = mv
    counts = {}
    for mask in range(1 << m):
        bits = [i for i in range(m) if (mask >> i) & 1]
        if any(nbmask[i] & mask for i in bits):
            continue
        k = len(bits)
        counts[k] = counts.get(k, 0) + 1
    if not counts:
        return [1]
    top = max(counts)
    return [counts.get(k, 0) for k in range(top + 1)]


def leaves_and_supports(adj, n):
    return [(v, next(iter(adj[v]))) for v in range(n) if len(adj[v]) == 1]


def closed_nbhd(adj, v):
    return {v} | set(adj[v])


def evaluate_row(n, edges, p, cross_check=True):
    adj = adjacency(n, edges)
    full = set(range(n))
    polyT = dp_indep_poly(adj, full)
    xT = first_strict_descent(polyT)
    governed = p >= xT + 2

    F, S, S_brute = [], 0, 0
    brute_ok = bool(cross_check)
    leaf_rows = []
    for v, s_v in leaves_and_supports(adj, n):
        Tv = full - {v}
        a_v = delta(dp_indep_poly(adj, Tv), p)
        Hv = full - {v, s_v}
        b_v = delta(dp_indep_poly(adj, Hv), p - 1)
        Nsv = full - closed_nbhd(adj, s_v)
        B_sv = delta(dp_indep_poly(adj, Nsv), p - 1)
        g_v = b_v - B_sv
        favorable = a_v < 0
        if favorable:
            F.append(v)
            S += g_v
        if cross_check and brute_ok:
            b_Tv, b_Hv, b_Nsv = (brute_indep_poly(adj, Tv),
                                  brute_indep_poly(adj, Hv),
                                  brute_indep_poly(adj, Nsv))
            if b_Tv is None or b_Hv is None or b_Nsv is None:
                brute_ok = False
            else:
                a_v_b, b_v_b, B_sv_b = (delta(b_Tv, p), delta(b_Hv, p - 1),
                                         delta(b_Nsv, p - 1))
                if (a_v_b, b_v_b, B_sv_b) != (a_v, b_v, B_sv):
                    raise AssertionError(
                        f"cross-check mismatch at leaf {v}: "
                        f"DP=({a_v},{b_v},{B_sv}) brute=({a_v_b},{b_v_b},{B_sv_b})")
                if favorable:
                    S_brute += b_v_b - B_sv_b
        leaf_rows.append(dict(v=v, s_v=s_v, a_v=a_v, b_v=b_v, B_sv=B_sv,
                               g_v=g_v, favorable=favorable))

    return dict(n=n, x=xT, p=p, governed=governed, leaf_rows=leaf_rows, F=F,
                num_favorable=len(F), S=S,
                S_brute=(S_brute if brute_ok else None),
                cross_check_agrees=(brute_ok and S_brute == S) if brute_ok else None)


def bridge1_counts(n, edges, v, s_v, r):
    """|C_r(v)| via BRIDGE-1: i_r(H_v) - i_r(T - N[s_v])."""
    adj = adjacency(n, edges)
    full = set(range(n))
    Hv = full - {v, s_v}
    Nsv = full - closed_nbhd(adj, s_v)
    return coef(dp_indep_poly(adj, Hv), r) - coef(dp_indep_poly(adj, Nsv), r)


