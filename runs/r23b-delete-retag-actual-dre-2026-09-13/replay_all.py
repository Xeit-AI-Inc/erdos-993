def pruefer_decode(n, seq):
    degree = [1] * n
    for x in seq:
        degree[x] += 1
    edges = []
    import heapq
    leaves = [i for i in range(n) if degree[i] == 1]
    heapq.heapify(leaves)
    for x in seq:
        leaf = heapq.heappop(leaves)
        edges.append((leaf, x))
        degree[leaf] -= 1
        degree[x] -= 1
        if degree[x] == 1:
            heapq.heappush(leaves, x)
    remaining = [i for i in range(n) if degree[i] == 1]
    edges.append((remaining[0], remaining[1]))
    return edges


def pruefer_exhaustive(n):
    """All labeled trees on n vertices via exhaustive Pruefer sequences."""
    if n < 2:
        return
    for seq in itertools.product(range(n), repeat=n - 2):
        yield pruefer_decode(n, list(seq))


