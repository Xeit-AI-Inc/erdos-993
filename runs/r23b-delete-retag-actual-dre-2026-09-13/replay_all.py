def bridge_check_instance(n, edges, p):
    """Literal active-set enumeration vs the coefficient identity, plus
    |P| - |N| = S, on one (T, p) instance. Returns True/False/None
    (None = ungoverned, excluded from the sample)."""
    adj = adjacency(n, edges)
    xT = first_strict_descent(dp_indep_poly(adj, set(range(n))))
    if p < xT + 2:
        return None
    es = set(map(frozenset, edges))

    def ind_sets(vertices, r):
        for S in itertools.combinations(vertices, r):
            if all(frozenset(e) - set(S) for e in es if frozenset(e) <= set(vertices)):
                yield S

    Ptot = Ntot = Sagg = 0
    ok = True
    for v in range(n):
        if len(adj[v]) != 1:
            continue
        s = next(iter(adj[v]))
        full = set(range(n))
        a_v = delta(dp_indep_poly(adj, full - {v}), p)
        if a_v >= 0:
            continue
        W = [w for w in adj[s] if w != v]
        Hverts = [u for u in range(n) if u not in (v, s)]
        Cp = sum(1 for A in ind_sets(Hverts, p) if set(A) & set(W))
        Cp1 = sum(1 for A in ind_sets(Hverts, p - 1) if set(A) & set(W))
        b_v = delta(dp_indep_poly(adj, full - {v, s}), p - 1)
        B_s = delta(dp_indep_poly(adj, full - closed_nbhd(adj, s)), p - 1)
        g_v = b_v - B_s
        if Cp - Cp1 != g_v:
            ok = False
        Ptot += Cp
        Ntot += Cp1
        Sagg += g_v
    return ok and (Ptot - Ntot == Sagg)


