def hub_satellite_family(m):
    """Order-91 control family (SOLUTION-CONTRACT.md section 6; m=22 -> n=91):
    hub 0; arm 0-1(s)-2(v); m satellites c_i each with 3 pendant leaves, all
    attached to hub 0. n(m) = 3 + 4*m."""
    edges = [(0, 1), (1, 2)]
    nid = 3
    for _ in range(m):
        c = nid
        nid += 1
        edges.append((0, c))
        for _ in range(3):
            edges.append((c, nid))
            nid += 1
    return nid, edges


def build_CB(j, k):
    """hub 0; arm 0-1(s)-2(v); k chokes; each choke j supports; each support
    exactly one leaf. n = 3 + k + 2*j*k.
    Returns (n, edges, v, s, hub)."""
    hub, s, v = 0, 1, 2
    edges = [(hub, s), (s, v)]
    nxt = 3
    for _ in range(k):
        z = nxt
        nxt += 1
        edges.append((hub, z))
        for _ in range(j):
            y, u = nxt, nxt + 1
            nxt += 2
            edges += [(z, y), (y, u)]
    return nxt, edges, v, s, hub


